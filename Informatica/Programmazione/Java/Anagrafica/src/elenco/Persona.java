package elenco;

public class Persona {

    // ATTRIBUTI: nome, cognome, età, altezza
    private String nome;
    private String cognome;
    private int eta;
    private float  altezza;

    // METODI



    // COSTRUTTORE
    public Persona (String n, String c, int e, float a) {
        nome = n;
        cognome = c;
        eta = e;
        altezza = a;

    }
}
